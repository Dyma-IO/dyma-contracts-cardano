#!/usr/bin/env python3
"""Writes lib/dyma/math_vectors.ak: one Aiken test per vector of fixtures/escrow-math.json.

The fixture is a byte-identical copy of dyma-contracts' (the CosmWasm escrow and Dyma's
TypeScript preview check the same vectors). CI regenerates this module and fails on any diff.
Usage: scripts/gen-math-vectors.py [--check]
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "fixtures" / "escrow-math.json"
TARGET = ROOT / "lib" / "dyma" / "math_vectors.ak"


def ident(name: str) -> str:
    return "vector_" + re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def ints(values) -> str:
    return "[" + ", ".join(str(int(v)) for v in values) + "]"


lines = [
    "//// Generated by scripts/gen-math-vectors.py from fixtures/escrow-math.json: do not edit.",
    "//// The same vectors run against the CosmWasm escrow and Dyma's TypeScript preview.",
    "",
    "use dyma/math.{bps_of, distribute_all, finalize_snapshot}",
    "",
]
for vector in json.loads(FIXTURE.read_text()):
    d = int(vector["D"])
    weights = [int(w) for w in vector["weights"]]
    cap_bps = int(vector["capBps"])
    min_payout = int(vector["minPayout"])
    fee_bps = int(vector.get("feeBps", 0))
    gross = int(vector.get("B", d))
    checks = []
    if "B" in vector:
        checks += [
            f"snapshot.fee == {int(vector['fee'])}",
            f"snapshot.distributable == {d}",
            f"snapshot.cap == {int(vector['cap'])}",
        ]
    checks += [
        f"result.amounts == {ints(vector['amounts'])}",
        f"result.skipped == {int(vector['skipped'])}",
        f"result.leftover == {int(vector['leftover'])}",
        f"bps_of(result.paid_total, {fee_bps}) == {int(vector['feeCharged'])}",
        f"{gross} - result.paid_total - bps_of(result.paid_total, {fee_bps}) == {int(vector['ownerRefund'])}",
    ]
    lines += [
        f"/// {vector['name']}: {vector['source']}" + (f" ({vector['note']})" if vector.get("note") else ""),
        f"test {ident(vector['name'])}() {{",
        f"  let snapshot = finalize_snapshot({gross}, {fee_bps}, {cap_bps})",
        f"  let result = distribute_all(snapshot.distributable, {ints(weights)}, snapshot.cap, {min_payout})",
        "  and {",
        f"    snapshot.distributable == {d},",
        f"    snapshot.cap == {int(vector['cap'])},",
        *[f"    {check}," for check in checks],
        "  }",
        "}",
        "",
    ]
text = "\n".join(lines).rstrip() + "\n"
# Formatted like the rest of the code base (`aiken fmt --check` runs in CI).
text = subprocess.run(
    ["aiken", "fmt", "--stdin"], input=text, capture_output=True, text=True, check=True
).stdout
if "--check" in sys.argv:
    if not TARGET.exists() or TARGET.read_text() != text:
        sys.exit("lib/dyma/math_vectors.ak is out of date: run scripts/gen-math-vectors.py")
    print("math vectors up to date")
else:
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)}")
